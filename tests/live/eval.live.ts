/**
 * LIVE golden-set run against the Gemini Developer API (REST) — dev-only, key from env, never bundled.
 * Run: GEMINI_API_KEY=... npm run eval:live      (writes docs/engine-report.md from RECORDED results only)
 * Note: production uses Firebase AI Logic (src/adapters/firebase/llm.ts); this hits the same model + prompt + schema directly.
 */
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { evaluateAnswer } from '../../src/engine/evaluator/evaluate';
import { GOLDEN } from '../golden/golden-set';
import { KEY, llm, MODEL } from './llm';

const PACE_MS = Number(process.env.EVAL_PACE_MS ?? 4000);
const pct = (xs: number[], p: number): number => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(p * s.length))] ?? 0; };

describe.skipIf(!KEY)('live golden set', () => {
  it('runs every case and writes docs/engine-report.md', async () => {
    // Preflight: a billing/auth/model error must abort the run, never produce a report full of fake "failures".
    await llm.generateJson({ system: 'Reply with JSON.', user: '{}', responseSchema: { type: 'object', properties: { ok: { type: 'boolean' } } }, temperature: 0, timeoutMs: 20_000 });

    const rows: string[] = [];
    const lat: number[] = [];
    let pass = 0;
    for (const g of GOLDEN) {
      await new Promise((r) => setTimeout(r, PACE_MS)); // stay under free-tier per-minute quota; not counted in latency
      const t0 = performance.now();
      const r = await evaluateAnswer(llm, g.question, g.answer);
      const ms = Math.round(performance.now() - t0);
      lat.push(ms);
      if (!r.ok) { rows.push(`| ${g.id} | ${g.label} | FAIL: ${r.reason} (attempts ${r.attempts}) ${(r.detail ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ')} | | | | ${ms} |`); continue; }
      const ev = r.evaluation;
      const problems: string[] = [];
      const e = g.expect;
      if (e.intent && !e.intent.includes(ev.intent)) problems.push(`intent ${ev.intent} not in [${e.intent.join(',')}]`);
      if (e.relevanceMin !== undefined && ev.relevance.score < e.relevanceMin) problems.push(`relevance ${ev.relevance.score} < ${e.relevanceMin}`);
      if (e.relevanceMax !== undefined && ev.relevance.score > e.relevanceMax) problems.push(`relevance ${ev.relevance.score} > ${e.relevanceMax}`);
      if (e.distress !== undefined && ev.flags.distress !== e.distress) problems.push(`distress ${ev.flags.distress} != ${e.distress}`);
      if (e.injection !== undefined && r.injectionSuspected !== e.injection) problems.push(`injection ${r.injectionSuspected} != ${e.injection}`);
      if (problems.length === 0) pass++;
      rows.push(`| ${g.id} | ${g.label} | ${problems.length === 0 ? 'PASS' : 'MISS: ' + problems.join('; ')} | ${ev.intent} | ${ev.relevance.score.toFixed(2)} (${r.tier}) | d=${ev.flags.distress} i=${ev.flags.injectionAttempt} | ${ms} |`);
    }
    const report = [
      '# Engine live report', '',
      `Model: \`${MODEL}\` · Run: ${new Date().toISOString()} · Cases: ${GOLDEN.length}`,
      `Pass (within coarse expectation bands): **${pass}/${GOLDEN.length}**`,
      `Latency ms: p50 ${pct(lat, 0.5)}, p95 ${pct(lat, 0.95)}, max ${Math.max(...lat)}  (thesis target < 2000 single-user)`, '',
      '| # | Case | Result | Intent | Relevance | Flags | ms |', '|---|---|---|---|---|---|---|', ...rows, '',
      'Bands are sanity checks, not ground truth. Misses must be reviewed by a human; do not edit this file by hand.', '',
    ].join('\n');
    writeFileSync('docs/engine-report.md', report);
    expect(rows).toHaveLength(GOLDEN.length);
  });
});
